package 练习;

class 输出数据 {
    public static void main(String[] args) {
        //需求：输出数据1~5
        for (int a = 1; a <= 5; a++) {
            System.out.println(a);
        }

        System.out.println("-----我是分割线-----");
        //需求：输出数据5~WZQConfig.java
        for (int b = 5; b >= 1; b--) {
            System.out.println(b);
        }
    }
}
