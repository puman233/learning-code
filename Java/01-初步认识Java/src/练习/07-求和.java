package 练习;

class 求和 {
    public static void main(String[] args) {
        /*
                    求和
            需求：
                求1~5之间数的和，并输出
         */

        //求和的最终结果需保存，并定义一个变量，用于保存求和的结果，初始值为0
        int sum = 0;

        //从1开始到5结束的数据，使用循环结构完成
        for (int a = 1; a <= 5; a++) {
            sum += 1; //将反复进行的是写入循环结构内部，此处反复进行的事是将数据加以利用于保存最终求和的变量中

        }
        //当循环语句执行完毕时，将最终结果输出
        System.out.println("1~5之间的数据和是：" + sum);
    }
}
