/*
    常量分类:
字符串常量:用双引号括起来的内容
    Eg:"HelloWorld"
整数常量:不带小数部分的数字
    Eg:2020
小数常量:带小数部分的数字
    Eg:3.14
字符常量:用单引号括起来的内容
    Eg:'A'
布尔常量:布尔值,表示真假
    ps:只有两个值:True,False
空常量:一个特殊的值,空值
    ps:值为:null
*/

class Hello{
    public static void main(String[] args){
        //字符串常量
        System.out.println("HelloWorld");
        System.out.println("打印第一个HelloWorld");
    }
}
class 常量_2{
    public static void main(String[] args){
        //整数,小数常量
        System.out.println(2020);
        System.out.println(3.14);
        //布尔常量
        System.out.println("Ture");
        System.out.println("False");
        //空常量
        System.out.println("null");
    }
}

