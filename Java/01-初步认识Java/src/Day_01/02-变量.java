/*
    变量的使用
- 取值个修改值
- 取值格式:变量名
    Eg: a
- 修改值格式:变量名 = 变量值
    Eg: a = 2020
 */

class 变量_2{
    public static void main(String[] args){
        //定义变量
        int a = 2020;

        //输出变量
        System.out.println(a);

        //修改变量
        a = 360;
        System.out.println(a);

        int b = 2025;
        System.out.println(b);

        int bot = b;
        System.out.println(bot);
    }
}
