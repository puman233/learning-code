"""
模式      描述
r       以只读方式打开文件
rb      以二进制格式打开一个文件用于只读
r+      打开一个文件用于读写
rb+     以二进制格式打开一个文件用于读写
w       打开一个文件只用于写入
wb      以二进制格式打开一个文件只用于写入
w+      打开一个文件用于读写
wb+     以二进制格式打开一个文件用于读写
a       打开一个文件用于追加
ab      以二进制格式打开一个文件用于追加
a+      打开一个文件用于读写
ab+     以二进制格式打开一个文件用于追加

说明：
文件指针：相当于鼠标光标的位置
    其中 r & rb & r+ & rb+ 的文件指针都在文件开头
    而 a & ab & a+ & ab+ 的文件指针都在文件结尾
"""