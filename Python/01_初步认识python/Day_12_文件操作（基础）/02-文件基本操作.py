"""
文件操作步骤：
    打开文件
    读写等操作
    关闭文件
注意：
    可以只打开和关闭文件，不进行任何读写作用
"""
"""
在Python中，使用open函数，可以打开一个已经打开的文件，或者创建一个文件，语法如下：
    open(name,mode)
name 打开的目标文件名的字符串（可以包括文件所在的具体路径）
mode 设置打开文件的模式（访问模式）：只读、写入、追加等
"""
f = open('test.txt', 'w')   # 打开 open()

f.write('HelloWorld')   # 读写操作

f.close()   # 关闭

