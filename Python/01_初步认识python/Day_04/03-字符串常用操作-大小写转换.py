"""
    capitalize():   将字符串第一个字符转换成大写
        capital initial

    title():    将字符串每个单词首字母转换成大写

    lower():    将字符串中大写转小写

    upper():    将字符串中小写转大写

    lstrip():   删除字符串左侧空白字符
"""

my_star = "hello world and my Python"

# capitalize()
new_star = my_star.capitalize()
print(new_star)

# title()
new_star2 = my_star.title()
print(new_star2)

# lower()
new_star3 = my_star.lower()
print(new_star3)

# upper()
new_star4 = my_star.upper()
print(new_star4)

# lstrip()
new_star5 = my_star.lstrip()
print(new_star5)

